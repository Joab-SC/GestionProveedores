-- Como ejecutarlo (conectar COMO el usuario de la aplicacion):
--   sqlplus Joab/Joab2007@localhost:1521/FREEPDB1
--   SQL> @01_schema.sql
--
-- El script puede ejecutarse sobre una base vacia; el paso 1 ademas
-- borra las tablas del proyecto si ya existen, para poder re-ejecutarlo.
-- =====================================================================

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET FEEDBACK ON

-- ---------------------------------------------------------------------
-- 1) Borra el esquema anterior (si existe) para poder re-ejecutar
-- ---------------------------------------------------------------------
DECLARE
  PROCEDURE borrar_tabla(p_tabla IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE ' || p_tabla || ' CASCADE CONSTRAINTS';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLCODE != -942 THEN   -- -942: la tabla no existe todavia
        RAISE;
      END IF;
  END;
BEGIN
  borrar_tabla('bitacora');
  borrar_tabla('usuario');
  borrar_tabla('detalle_tipo_usuario');
  borrar_tabla('permiso');
  borrar_tabla('tipo_usuario');
  borrar_tabla('detalle_producto');
  borrar_tabla('proveedor');
  borrar_tabla('producto');
  borrar_tabla('categoria_producto');
  borrar_tabla('ciudad');
END;
/

-- ---------------------------------------------------------------------
-- 2) Tablas
-- ---------------------------------------------------------------------

-- Ciudades (las identidades generan los ids: 1, 2, 3, ...)
CREATE TABLE ciudad (
  id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre  VARCHAR2(80) NOT NULL,
  CONSTRAINT pk_ciudad PRIMARY KEY (id),
  CONSTRAINT uq_ciudad_nombre UNIQUE (nombre)
);

CREATE TABLE categoria_producto (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre      VARCHAR2(60) NOT NULL,
  descripcion VARCHAR2(250),
  CONSTRAINT pk_categoria_producto PRIMARY KEY (id),
  CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);

CREATE TABLE producto (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  nombre       VARCHAR2(100) NOT NULL,
  descripcion  VARCHAR2(250),
  categoria_id NUMBER NOT NULL,
  CONSTRAINT pk_producto PRIMARY KEY (id),
  CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id)
      REFERENCES categoria_producto (id)
);
CREATE INDEX ix_producto_categoria ON producto (categoria_id);

CREATE TABLE proveedor (
  cedula           VARCHAR2(15) NOT NULL,
  nombre           VARCHAR2(60) NOT NULL,
  apellido         VARCHAR2(60) NOT NULL,
  fecha_nacimiento DATE NOT NULL,
  ciudad_id        NUMBER NOT NULL,
  CONSTRAINT pk_proveedor PRIMARY KEY (cedula),
  CONSTRAINT fk_proveedor_ciudad FOREIGN KEY (ciudad_id)
      REFERENCES ciudad (id)
);
CREATE INDEX ix_proveedor_ciudad ON proveedor (ciudad_id);

-- Relacion N-M entre proveedor y producto; ON DELETE CASCADE para que
-- borrar un producto/proveedor limpie sus asignaciones.
CREATE TABLE detalle_producto (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  producto_id      NUMBER NOT NULL,
  proveedor_cedula VARCHAR2(15) NOT NULL,
  CONSTRAINT pk_detalle_producto PRIMARY KEY (id),
  CONSTRAINT uq_dp UNIQUE (producto_id, proveedor_cedula),
  CONSTRAINT fk_dp_producto FOREIGN KEY (producto_id)
      REFERENCES producto (id) ON DELETE CASCADE,
  CONSTRAINT fk_dp_proveedor FOREIGN KEY (proveedor_cedula)
      REFERENCES proveedor (cedula) ON DELETE CASCADE
);
CREATE INDEX ix_dp_proveedor ON detalle_producto (proveedor_cedula);

CREATE TABLE tipo_usuario (
  id     NUMBER NOT NULL,
  nombre VARCHAR2(40) NOT NULL,
  CONSTRAINT pk_tipo_usuario PRIMARY KEY (id),
  CONSTRAINT uq_tipo_usuario_nombre UNIQUE (nombre)
);

CREATE TABLE permiso (
  id     NUMBER NOT NULL,
  nombre VARCHAR2(40) NOT NULL,
  CONSTRAINT pk_permiso PRIMARY KEY (id),
  CONSTRAINT uq_permiso_nombre UNIQUE (nombre)
);

-- Relacion N-M tipo_usuario - permiso
CREATE TABLE detalle_tipo_usuario (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
  tipo_usuario_id NUMBER NOT NULL,
  permiso_id      NUMBER NOT NULL,
  CONSTRAINT pk_detalle_tipo_usuario PRIMARY KEY (id),
  CONSTRAINT uq_dtu UNIQUE (permiso_id, tipo_usuario_id),
  CONSTRAINT fk_dtu_tipo_usuario FOREIGN KEY (tipo_usuario_id)
      REFERENCES tipo_usuario (id),
  CONSTRAINT fk_dtu_permiso FOREIGN KEY (permiso_id)
      REFERENCES permiso (id)
);

CREATE TABLE usuario (
  cedula           VARCHAR2(15) NOT NULL,
  nombre           VARCHAR2(60) NOT NULL,
  apellido         VARCHAR2(60) NOT NULL,
  fecha_nacimiento DATE NOT NULL,
  ciudad_id        NUMBER NOT NULL,
  tipo_usuario_id  NUMBER NOT NULL,
  contrasena       VARCHAR2(64) NOT NULL,   -- hash SHA-256 en hex minuscula
  activo           NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT pk_usuario PRIMARY KEY (cedula),
  CONSTRAINT ck_usuario_activo CHECK (activo IN (0, 1)),
  CONSTRAINT fk_usuario_ciudad FOREIGN KEY (ciudad_id)
      REFERENCES ciudad (id),
  CONSTRAINT fk_usuario_tipo FOREIGN KEY (tipo_usuario_id)
      REFERENCES tipo_usuario (id)
);
CREATE INDEX ix_usuario_ciudad ON usuario (ciudad_id);
CREATE INDEX ix_usuario_tipo ON usuario (tipo_usuario_id);

-- Solo un usuario activo de tipo 1 (Administrador). El indice es
-- unico sobre la expresion: los demas tipos producen NULL y NULL no
-- compite en un indice unico.
CREATE UNIQUE INDEX uq_un_solo_admin ON usuario
  (CASE tipo_usuario_id WHEN 1 THEN 1 END);

CREATE TABLE bitacora (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  usuario_cedula VARCHAR2(15) NOT NULL,
  fecha_entrada  TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  fecha_salida   TIMESTAMP(6),
  CONSTRAINT pk_bitacora PRIMARY KEY (id),
  CONSTRAINT ck_bitacora_fechas
      CHECK (fecha_salida IS NULL OR fecha_salida >= fecha_entrada),
  CONSTRAINT fk_bitacora_usuario FOREIGN KEY (usuario_cedula)
      REFERENCES usuario (cedula)
);
CREATE INDEX ix_bitacora_usuario ON bitacora (usuario_cedula);

